//! All key bindings, in one place (VS Code-style, spec section 5.3 and 6).

use gpui_kit::{App, KeyBinding};

use crate::editor::actions::*;
use crate::workspace::{
	CloseTab, CommandPalette, GoBack, GoForward, NewNote, NextTab, OpenSettings, PrevTab,
	QuickOpen, ReopenClosedTab, SearchVault, ToggleLeftPanel, ToggleRightPanel,
};

pub fn bind(cx: &mut App) {
	cx.bind_keys([
		KeyBinding::new("ctrl-w", CloseTab, Some("Workspace")),
		KeyBinding::new("ctrl-tab", NextTab, Some("Workspace")),
		KeyBinding::new("ctrl-shift-tab", PrevTab, Some("Workspace")),
		KeyBinding::new("ctrl-shift-t", ReopenClosedTab, Some("Workspace")),
		KeyBinding::new("alt-left", GoBack, Some("Workspace")),
		KeyBinding::new("alt-right", GoForward, Some("Workspace")),
		KeyBinding::new("ctrl-shift-e", ToggleLeftPanel, Some("Workspace")),
		KeyBinding::new("ctrl-alt-b", ToggleRightPanel, Some("Workspace")),
		KeyBinding::new("ctrl-,", OpenSettings, Some("Workspace")),
		KeyBinding::new("ctrl-p", QuickOpen, Some("Workspace")),
		KeyBinding::new("ctrl-shift-p", CommandPalette, Some("Workspace")),
		KeyBinding::new("ctrl-shift-f", SearchVault, Some("Workspace")),
		KeyBinding::new("ctrl-n", NewNote, Some("Workspace")),
	]);
	let e = Some("NoteEditor");
	cx.bind_keys([
		KeyBinding::new("left", MoveLeft, e),
		KeyBinding::new("right", MoveRight, e),
		KeyBinding::new("shift-left", SelectLeft, e),
		KeyBinding::new("shift-right", SelectRight, e),
		KeyBinding::new("ctrl-left", MoveWordLeft, e),
		KeyBinding::new("ctrl-right", MoveWordRight, e),
		KeyBinding::new("ctrl-shift-left", SelectWordLeft, e),
		KeyBinding::new("ctrl-shift-right", SelectWordRight, e),
		KeyBinding::new("home", MoveLineStart, e),
		KeyBinding::new("end", MoveLineEnd, e),
		KeyBinding::new("shift-home", SelectLineStart, e),
		KeyBinding::new("shift-end", SelectLineEnd, e),
		KeyBinding::new("ctrl-home", MoveDocStart, e),
		KeyBinding::new("ctrl-end", MoveDocEnd, e),
		KeyBinding::new("ctrl-shift-home", SelectDocStart, e),
		KeyBinding::new("ctrl-shift-end", SelectDocEnd, e),
		KeyBinding::new("up", MoveUp, e),
		KeyBinding::new("down", MoveDown, e),
		KeyBinding::new("shift-up", SelectUp, e),
		KeyBinding::new("shift-down", SelectDown, e),
		KeyBinding::new("pageup", PageUp, e),
		KeyBinding::new("pagedown", PageDown, e),
		KeyBinding::new("shift-pageup", SelectPageUp, e),
		KeyBinding::new("shift-pagedown", SelectPageDown, e),
		KeyBinding::new("backspace", Backspace, e),
		KeyBinding::new("shift-backspace", Backspace, e),
		KeyBinding::new("delete", Delete, e),
		KeyBinding::new("ctrl-backspace", DeleteWordLeft, e),
		KeyBinding::new("ctrl-delete", DeleteWordRight, e),
		KeyBinding::new("enter", Newline, e),
		KeyBinding::new("shift-enter", Newline, e),
		KeyBinding::new("tab", Tab, e),
		KeyBinding::new("ctrl-a", SelectAll, e),
		KeyBinding::new("ctrl-c", Copy, e),
		KeyBinding::new("ctrl-x", Cut, e),
		KeyBinding::new("ctrl-v", Paste, e),
		KeyBinding::new("shift-tab", ShiftTab, e),
		KeyBinding::new("ctrl-z", Undo, e),
		KeyBinding::new("ctrl-y", Redo, e),
		KeyBinding::new("ctrl-shift-z", Redo, e),
		KeyBinding::new("ctrl-d", AddNextOccurrence, e),
		KeyBinding::new("ctrl-shift-l", SelectAllOccurrences, e),
		KeyBinding::new("escape", CollapseSelections, e),
		KeyBinding::new("ctrl-alt-up", AddCursorAbove, e),
		KeyBinding::new("ctrl-alt-down", AddCursorBelow, e),
		KeyBinding::new("alt-up", MoveLinesUp, e),
		KeyBinding::new("alt-down", MoveLinesDown, e),
		KeyBinding::new("shift-alt-up", CopyLinesUp, e),
		KeyBinding::new("shift-alt-down", CopyLinesDown, e),
		KeyBinding::new("ctrl-shift-k", DeleteLines, e),
		KeyBinding::new("ctrl-enter", InsertLineBelow, e),
		KeyBinding::new("ctrl-shift-enter", InsertLineAbove, e),
		KeyBinding::new("ctrl-l", SelectLines, e),
		KeyBinding::new("ctrl-]", IndentLines, e),
		KeyBinding::new("ctrl-[", OutdentLines, e),
		KeyBinding::new("ctrl-b", Bold, e),
		KeyBinding::new("ctrl-i", Italic, e),
		KeyBinding::new("ctrl-k", InsertLink, e),
		KeyBinding::new("ctrl-e", ToggleLivePreview, e),
		KeyBinding::new("ctrl-f", Find, e),
		KeyBinding::new("ctrl-h", Replace, e),
		KeyBinding::new("f3", FindNext, e),
		KeyBinding::new("shift-f3", FindPrevious, e),
	]);
}
